import requests
from bs4 import BeautifulSoup
import time
from urllib.parse import urljoin, urlparse

seed_url = "https://www.metrotvnews.com"
headers = {'User-Agent': user_agent}

visited_urls = set()
frontier = [seed_url]
crawled_data = []
link_graph = {}

MAX_PAGES = 200
CRAWL_DELAY = 2

def is_internal_url(url):
    return "metrotvnews.com" in urlparse(url).netloc

print("Memulai proses crawling...")
doc_counter = 0

while frontier and len(crawled_data) < MAX_PAGES:
    current_url = frontier.pop(0).split('#')[0].rstrip('/')

    if current_url in visited_urls:
        continue

    if not rp.can_fetch(user_agent, current_url):
        continue

    try:
        response = requests.get(current_url, headers=headers, timeout=10)
        time.sleep(CRAWL_DELAY)

        if response.status_code != 200 or 'text/html' not in response.headers.get('Content-Type', ''):
            continue

        visited_urls.add(current_url)
        soup = BeautifulSoup(response.text, 'html.parser')

        for element in soup(["script", "style", "nav", "footer", "header", "aside", "form"]):
            element.decompose()

        title_elem = soup.find('h1') or soup.find('title')
        title = title_elem.get_text(strip=True) if title_elem else "Tanpa Judul"

        date_elem = soup.find('meta', {'property': 'article:published_time'}) or soup.find('time')
        date_str = date_elem['content'] if date_elem and date_elem.has_attr('content') else (date_elem.get_text(strip=True) if date_elem else "Tanggal tidak ditemukan")

        paragraphs = soup.find_all('p')
        full_text = ' '.join([p.get_text(strip=True) for p in paragraphs if len(p.get_text(strip=True)) > 25])

        internal_links = set()
        for a_tag in soup.find_all('a', href=True):
            href = a_tag['href']
            full_link = urljoin(current_url, href).split('#')[0].rstrip('/')

            if is_internal_url(full_link) and full_link.startswith("http"):
                internal_links.add(full_link)
                if full_link not in visited_urls and full_link not in frontier:
                    frontier.append(full_link)

        if len(full_text) > 100:
            doc_id = f"doc_{doc_counter + 1}"
            crawled_data.append({
                'doc_id': doc_id,
                'url': current_url,
                'title': title,
                'date': date_str,
                'text': full_text
            })
            link_graph[current_url] = list(internal_links)
            doc_counter += 1
            print(f"[{doc_counter}/{MAX_PAGES}] Berhasil: {title[:45]}...")

    except Exception as e:
        pass

print(f"\nCrawling selesai. Total dokumen berhasil disimpan: {len(crawled_data)}")

import re
from Sastrawi.Stemmer.StemmerFactory import StemmerFactory
from Sastrawi.StopWordRemover.StopWordRemoverFactory import StopWordRemoverFactory
from collections import defaultdict

stemmer = StemmerFactory().create_stemmer()
stopword_remover = StopWordRemoverFactory().create_stop_word_remover()

def preprocess_text(text):
    text = re.sub(r'[^a-z\s]', '', text.lower())
    text = stopword_remover.remove(text)
    text = stemmer.stem(text)
    return text.split()

inverted_index = defaultdict(set)

print("Melakukan praproses teks dan membuat Inverted Index...")
for doc in crawled_data:
    doc_id = doc['doc_id']
    content = f"{doc['title']} {doc['text']}"
    tokens = preprocess_text(content)

    for token in set(tokens):
        inverted_index[token].add(doc_id)

print(f"Inverted Index berhasil dibangun dengan {len(inverted_index)} term unik.")

def get_shingles(text, k=3):
    words = text.lower().split()
    if len(words) < k:
        return set([' '.join(words)])
    return set([' '.join(words[i:i+k]) for i in range(len(words) - k + 1)])

def jaccard_similarity(set1, set2):
    if not set1 or not set2:
        return 0.0
    return len(set1.intersection(set2)) / len(set1.union(set2))

doc_shingles = {doc['doc_id']: get_shingles(f"{doc['title']} {doc['text']}", k=3) for doc in crawled_data}

near_duplicates = []
n = len(crawled_data)

for i in range(n):
    for j in range(i + 1, n):
        id1, id2 = crawled_data[i]['doc_id'], crawled_data[j]['doc_id']
        sim = jaccard_similarity(doc_shingles[id1], doc_shingles[id2])

        if sim > 0.8:
            near_duplicates.append((id1, id2, sim, crawled_data[i]['title'], crawled_data[j]['title']))

print("--- HASIL DETEKSI NEAR-DUPLICATE (Threshold > 0.8) ---")
if near_duplicates:
    for id1, id2, sim, t1, t2 in near_duplicates:
        print(f"[{id1} <-> {id2}] Jaccard Similarity: {sim:.4f}")
        print(f"  Judul A: {t1}")
        print(f"  Judul B: {t2}\n")
else:
    print("Tidak ada pasangan halaman near-duplicate dengan kemiripan > 0.8.")

import networkx as nx
import pandas as pd

G = nx.DiGraph()

for src_url, dst_urls in link_graph.items():
    for dst_url in dst_urls:
        if dst_url in link_graph:
            G.add_edge(src_url, dst_url)

pagerank_scores = nx.pagerank(G, alpha=0.85)

top_10 = sorted(pagerank_scores.items(), key=lambda x: x[1], reverse=True)[:10]

df_pagerank = pd.DataFrame(top_10, columns=['URL Halaman', 'Skor PageRank'])
